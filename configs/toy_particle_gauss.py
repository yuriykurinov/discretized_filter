"""
Игрушечная модель для фильтра частиц из раздела 4 статьи
(Борисов, Куринов, «Фильтрация специальных марковских скачкообразных процессов
по дискретизованным наблюдениям»): theta -- 3 состояния с непересекающимися
носителями Y, наблюдение имеет нулевой снос (стресс-тест) и дисперсию,
равную Y.

Эта конфигурация -- парная модель для сравнения сеточного фильтра и
фильтра частиц на одной и той же траектории (ноутбук particle_filter.ipynb):
Lambda, pi и наблюдение взяты из раздела 4 статьи (вариант с
непересекающимися носителями, рис. 4-5), шаг ht укрупнён относительно
статейного 2e-3 ради времени счёта.
"""
import numpy as np
from numba import njit

from discretized_filter.core.densities import ObsChannel, NORMAL

exp_id = 'toy_particle_gauss'

two_jumps = False

n_points = 2

T = 50

ht = 0.005

seed = 20260901

N = 3

# Нулевой снос -- стресс-тест на чистую фильтрацию по шуму
@njit(nogil=True, cache=True)
def zero_drift(t, y, theta):
    return np.zeros((y.shape[0], 1))


# Дисперсия равна значению Y (подынтегральное выражение в (3.2))
@njit(nogil=True, cache=True)
def var_xi(t, y, theta):
    return y[:, 0:1]


# Внедиагональные интенсивности перехода; диагональ строит сборщик конфига
Lambda = np.array([
    [0.0, 0.2, 0.2],
    [0.01, 0.0, 0.05],
    [0.15, 0.1, 0.0]
])

# Непересекающиеся носители Y по трём состояниям
y_intervals = [
    np.array([[0.1, 0.3],
              [0.3, 0.5],
              [0.5, 0.7]])
]

num1 = 64

pi_family = 'uniform'

channels = [
    ObsChannel(kind=NORMAL, drift=zero_drift, var=var_xi),
]
